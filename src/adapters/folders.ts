import { closeSync, openSync, readSync } from 'node:fs';
import { basename, join } from 'node:path';
import { ADAPTER_INTERFACE_VERSION, type Adapter, type ScanInput } from '../adapter.js';
import { CODE_FILE, cruiseWithoutConfig, type ImportScan } from '../cruise.js';
import { personalRules } from '../describe/prompt.js';
import type { FileKind, FileNode, Gap, Graph, GraphMeta, Part } from '../model.js';
import { ensureDir } from '../repo.js';
import { folderPartOf, folderPartsOf, listFiles, looksGenerated, packageDirsOf, readmeOf, readText, sha1, textFacts } from './files.js';

/** Files up to this size are read whole; bigger ones stay on the map, read in chunks for their hash. */
export const MAX_BYTES = 200_000;

/**
 * A file over MAX_BYTES as the map holds it: with its size, lines and hash,
 * and an info gap that says so. Generated by its name or header: kind
 * `generated`, so describe skips it. Null for a binary.
 */
export const largeFile = (root: string, path: string): { kind: FileKind; lines: number; hash: string; gap: Gap } | null => {
  const facts = textFacts(join(root, path));
  if (!facts) return null;
  const generated = looksGenerated(path, facts.head);
  const size = `${Math.round(facts.bytes / 1000)} KB`;
  return {
    kind: generated ? 'generated' : fileKindOf(path),
    lines: facts.lines,
    hash: facts.hash,
    gap: {
      kind: 'large-file',
      level: 'info',
      file: path,
      detail: generated
        ? `${size}, generated: on the map with its imports and links; describe skips it`
        : `${size}, over the ${MAX_BYTES / 1000} KB read whole: on the map with its imports and links; describe reads only its start`,
    },
  };
};

/** Text files worth describing in a repo without a code structure the map understands. */
const TEXT_FILE =
  /\.(lua|sh|bash|zsh|fish|py|rb|go|rs|el|vim|nix|ps1|js|mjs|cjs|ts|tsx|jsx|vue|svelte|md|txt|toml|ya?ml|ini|conf|cfg|service|timer|socket|json|sql|html|css)$/i;
/** Code a JS repo may hold besides JS/TS (scripts, a Python helper): listed, without links. */
const OTHER_CODE_FILE = /\.(lua|sh|bash|zsh|fish|py|rb|go|rs|el|nix|ps1)$/i;
const SKIPPED_FILE = /(^|\/)(package-lock\.json|pnpm-lock\.yaml|yarn\.lock|bun\.lockb?|Cargo\.lock|poetry\.lock|uv\.lock)$/;

/** An executable script without an extension (`bin/deploy`): its first line is a shebang. */
const isExtensionlessScript = (root: string, path: string): boolean => {
  const name = path.split('/').pop() ?? path;
  if (name.includes('.')) return false;
  let fd: number | null = null;
  try {
    fd = openSync(join(root, path), 'r');
    const head = Buffer.alloc(2);
    return readSync(fd, head, 0, 2, 0) === 2 && head.toString() === '#!';
  } catch {
    return false;
  } finally {
    if (fd !== null) closeSync(fd);
  }
};

export const fileKindOf = (path: string): FileKind => {
  const name = path.split('/').pop() ?? path;
  if (/(\.|_)(spec|test)\.\w+$/.test(name) || /^test_.*\.py$/.test(name) || /(^|\/)(__tests__|tests?)\//.test(path)) {
    return 'test';
  }
  if (name.endsWith('.d.ts') || /(^|\/)generated\//.test(path)) return 'generated';
  if (/\.(md|txt)$/i.test(name)) return 'doc';
  if (/\.(json|ya?ml|toml|ini|conf|cfg|service|timer|socket)$/i.test(name) || /\.config\.\w+$/.test(name)) {
    return 'config';
  }
  if (/\.(vue|svelte|tsx|jsx)$/.test(name)) return 'component';
  if (/\.(types?)\.\w+$/.test(name)) return 'type';
  if (/\.(sh|bash|zsh|fish|lua|py|rb|ps1)$/i.test(name) || !name.includes('.')) return 'script';
  return 'other';
};

const meta = (name: string, hasLinks: boolean): GraphMeta => ({
  title: `${name} map`,
  srcDir: '',
  sourceLabel: 'the repo',
  groups: [
    { kind: 'package', label: 'Packages' },
    { kind: 'folder', label: 'Folders' },
    { kind: 'root', label: 'Top level' },
  ],
  groupFlow: [
    ['package', 'folder'],
    ['folder', 'root'],
  ],
  servicesLabel: 'Services',
  operationsLabel: 'Server calls',
  boundary: null,
  library: null,
  hasLinks,
});

interface FolderAdapterOptions {
  /** 'js' follows imports with dependency-cruiser; 'plain' only lists folders and files. */
  mode: 'js' | 'plain';
  name?: string;
}

/**
 * Maps any repo by its folders: each workspace package, each folder under
 * src/, or each top-level folder is a part. The 'js' mode adds the imports
 * between JS/TS files; the 'plain' mode, for Lua, shell and Python repos,
 * only lists files and leaves the rest to the descriptions.
 */
export const folderAdapter = (repo: string, { mode, name = basename(repo) }: FolderAdapterOptions): Adapter => {
  const include = (root: string, path: string) => {
    if (SKIPPED_FILE.test(path)) return false;
    const byName = mode === 'js' ? CODE_FILE.test(path) || OTHER_CODE_FILE.test(path) : TEXT_FILE.test(path);
    return byName || isExtensionlessScript(root, path);
  };
  /** The parts come from the files the map holds; package.json files mark the packages among them. */
  const partsAt = (root: string) => {
    const files = listFiles(root);
    return folderPartsOf(files.filter((path) => include(root, path)), packageDirsOf(files));
  };
  const repoParts = partsAt(repo);

  const scan = async ({ root, artifacts, source }: ScanInput): Promise<Graph> => {
    const paths = listFiles(root).filter((path) => include(root, path));
    const partDirs = root === repo ? repoParts : partsAt(root);
    const gaps: Gap[] = [];
    let imports: ImportScan | null = null;
    if (mode === 'js' && paths.length > 0) {
      try {
        imports = cruiseWithoutConfig(root, ['.'], ensureDir(join(artifacts, 'scratch')));
      } catch (error) {
        gaps.push({ kind: 'imports-failed', level: 'warning', file: null, detail: `dependency-cruiser failed, so the map has no links: ${String(error).slice(0, 300)}` });
      }
    }

    const parts = new Map<string, Part>();
    const files: FileNode[] = [];
    const ids = new Set(paths);
    for (const path of paths) {
      let content: string | null;
      let large: ReturnType<typeof largeFile> = null;
      try {
        content = readText(join(root, path), MAX_BYTES);
        // Too big to read whole (a generated API client): still on the map, so imports of it resolve.
        if (content === null) large = largeFile(root, path);
      } catch (error) {
        // One file the scan can't read (no permission) leaves the map, with a note; the rest goes on.
        gaps.push({ kind: 'unreadable-file', level: 'warning', file: path, detail: `can't be read, so it isn't on the map: ${String(error).slice(0, 200)}` });
        continue;
      }
      if (content === null && !large) continue;
      if (large) gaps.push(large.gap);
      const part = folderPartOf(path, partDirs);
      const entry = parts.get(part.id) ?? { ...part, files: [] };
      entry.files.push(path);
      parts.set(part.id, entry);
      const fileImports = imports?.byFile.get(path);
      for (const specifier of fileImports?.unresolved ?? []) {
        gaps.push({ kind: 'unresolved-import', level: 'warning', file: path, detail: `import '${specifier}' does not resolve to a file` });
      }
      files.push({
        id: path,
        part: part.id,
        kind: large?.kind ?? fileKindOf(path),
        lines: large?.lines ?? (content as string).split('\n').length,
        hash: large?.hash ?? sha1(content as string),
        imports: (fileImports?.imports ?? []).filter((target) => ids.has(target)),
        libraries: fileImports?.libraries ?? [],
        components: [],
        operations: [],
        flags: [],
        registeredAs: null,
      });
    }

    const graph: Graph = {
      version: 1,
      generatedAt: new Date().toISOString(),
      meta: meta(name, mode === 'js'),
      source,
      backend: null,
      parts: [...parts.values()].sort((a, b) => a.id.localeCompare(b.id)),
      files,
      operations: [],
      routes: [],
      flags: [],
      subgraphs: [],
      cycles: imports?.cycles ?? [],
      gaps,
    };
    return graph;
  };

  return {
    interfaceVersion: ADAPTER_INTERFACE_VERSION,
    name: mode,
    scan,
    partOf: (path) => folderPartOf(path, repoParts).id,
    snapshotPaths: null,
    describeContext: async ({ repo: root }) => ({
      rules: personalRules(name),
      backgroundLabel: "The project's README:",
      background: readmeOf(root) || '(no README)',
      overviewLabel: 'README',
      overview: '',
    }),
  };
};

const JS = /\.(ts|tsx|mts|cts|js|jsx|mjs|cjs|vue|svelte)$/;
const OTHER_CODE = /\.(lua|sh|bash|zsh|fish|py|rb|go|rs|el|nix|ps1)$/;

/** 'js' when most of the code is JS/TS and there is a package.json, else 'plain'. */
export const chooseMode = (files: string[]): 'js' | 'plain' => {
  const js = files.filter((path) => JS.test(path) && !path.endsWith('.d.ts')).length;
  const other = files.filter((path) => OTHER_CODE.test(path)).length;
  const hasPackage = files.some((path) => /(^|\/)package\.json$/.test(path));
  return hasPackage && js >= 3 && js >= other ? 'js' : 'plain';
};

export const autoAdapter = (repo: string, name?: string): Adapter =>
  folderAdapter(repo, { mode: chooseMode(listFiles(repo)), name });
