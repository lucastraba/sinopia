// The primitives for a Vue + Vite + GraphQL stack, on a small todo app written for these tests.

const repos: string[] = [];
afterAll(() => {
  for (const repo of repos) rmSync(repo, { recursive: true, force: true });
});

const scan = async (files: Record<string, string>, map: string): Promise<Graph> => {
  const repo = mkdtempSync(join(tmpdir(), 'sinopia-primitives-'));
  repos.push(repo);
  for (const [path, content] of Object.entries({ 'package.json': '{ "name": "todo" }', ...files, [LOCAL_MAP]: map })) {
    mkdirSync(dirname(join(repo, path)), { recursive: true });
    writeFileSync(join(repo, path), content);
  }
  execFileSync('git', ['init', '-q'], { cwd: repo });
  const { adapter } = await pickAdapter('auto', repo, 'fixture');
  const graph = await adapter.scan({ repo, root: repo, artifacts: join(repo, '.artifacts'), source: { label: 'test', sha: null } });
  graph.gaps.push(...validateGraph(graph));
  return graph;
};

const linksOf = (graph: Graph, kind: string) =>
  graph.files.flatMap((f) => (f.links ?? []).filter((l) => l.kind === kind).map((l) => `${f.id} -> ${l.target} ${l.label}`)).sort();
const componentsOf = (graph: Graph) =>
  graph.files.flatMap((f) => f.components.map((c) => `${f.id} -> ${c.target} ${c.tag}${c.byName ? ' (by name)' : ''}`)).sort();
const gapsOf = (graph: Graph, kind: string) => graph.gaps.filter((g) => g.kind === kind).map((g) => `${g.level} ${g.file}: ${g.detail}`);
const errors = (graph: Graph) => graph.gaps.filter((g) => g.level === 'error');

const TSCONFIG = '{ "compilerOptions": { "paths": { "@/*": ["./src/*"] } } }';

describe('large files', () => {
  it('keeps a file over the read cap on the map, with the imports that point at it, and says so', async () => {
    const big = `// @generated by graphql-codegen\n${'export const filler = 1;\n'.repeat(12_000)}export const useTodosQuery = () => null;\n`;
    const graph = await scan(
      {
        'src/gql/client.ts': big,
        'src/TodoList.ts': "import { useTodosQuery } from './gql/client';\nexport const list = useTodosQuery();",
        'src/main.ts': "import { list } from './TodoList';\nconsole.log(list);",
      },
      'export default () => [];'
    );
    const client = graph.files.find((f) => f.id === 'src/gql/client.ts');
    expect(client).toMatchObject({ kind: 'generated', lines: 12_003 });
    expect(graph.files.find((f) => f.id === 'src/TodoList.ts')?.imports).toEqual(['src/gql/client.ts']);
    expect(gapsOf(graph, 'large-file')).toEqual([`info src/gql/client.ts: 300 KB, generated: on the map with its imports and links; describe skips it`]);
    expect(errors(graph)).toEqual([]);
  });
});

